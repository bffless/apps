#!/usr/bin/env node
// Strips CI's own comment envelope back off an apps-pr-review report before pr-review.yml
// posts it, so the workflow's header and footer are never duplicated.
//
// The agent is told to emit the report body and nothing else (Step 4 of
// .claude/agents/apps-pr-review.md), but it reads its own earlier comments to work out
// which round it is on (Step 2) — and those comments carry the wrapper. Copying what it
// sees there is a short step, and it has taken it: apps#662 posted the header twice, and
// apps#660 posted the whole review fenced as a ```markdown block, header and footer
// included, which GitHub renders as unreadable raw source.
//
// Instructions are the fix; this is the seatbelt. It only ever removes text this workflow
// is about to add back verbatim, so a well-behaved report passes through untouched.

import { readFileSync, writeFileSync, realpathSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const HEADER = '## 🤖 Automated apps review'
const FOOTER_MARK = '<sub>Generated by the `apps-pr-review` agent.'

/**
 * @param {string} report raw agent output
 * @returns {string} the report body, without CI's header, footer or an outer code fence
 */
export function stripReviewEnvelope(report) {
  let body = report

  // An outer ```markdown fence, opened before the report and closed after it. Only unwrap
  // when the fence encloses the WHOLE report: a fenced code block inside a review (a
  // suggested checklist entry, a shell snippet) is content, and must survive.
  const fence = body.match(/^\s*```[a-zA-Z]*\s*\n([\s\S]*)\n```\s*$/)
  if (fence && !fence[1].includes('\n```')) body = fence[1]

  // A preamble the agent wrote above the header ("Reviewing PR #660.") goes with it: the
  // header marks where the report really starts, so anything before it is chat, not review.
  const headerAt = body.indexOf(HEADER)
  if (headerAt !== -1) body = body.slice(headerAt + HEADER.length)

  const footerAt = body.indexOf(FOOTER_MARK)
  if (footerAt !== -1) {
    // Take the `---` separator with the footer when one immediately precedes it.
    const before = body.slice(0, footerAt)
    body = before.replace(/\n+-{3,}\s*$/, '')
  }

  return `${body.trim()}\n`
}

function main() {
  const [file] = process.argv.slice(2)
  if (!file) {
    console.error('usage: strip-review-envelope.mjs <report.md>')
    process.exit(2)
  }
  const original = readFileSync(file, 'utf8')
  const stripped = stripReviewEnvelope(original)
  if (stripped === original) return
  console.log(`strip-review-envelope: removed CI's envelope from ${file}`)
  writeFileSync(file, stripped)
}

function realOrSelf(path) {
  try {
    return realpathSync(path)
  } catch {
    return path
  }
}

// Only run when invoked as a script — the test imports stripReviewEnvelope. Realpaths on
// both sides so the guard survives a symlinked checkout (bffless/apps#401).
if (process.argv[1] && realOrSelf(process.argv[1]) === realOrSelf(fileURLToPath(import.meta.url))) {
  main()
}
