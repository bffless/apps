#!/usr/bin/env node
// Strips CI's own comment envelope back off an apps-pr-review report before pr-review.yml
// posts it, so the workflow's header and footer are never duplicated.
//
// The agent is told to emit the report body and nothing else (Step 4 of
// .claude/agents/apps-pr-review.md), but it reads its own earlier comments to work out
// which round it is on (Step 2) — and those comments carry the wrapper. Copying what it
// sees there is a short step, and it has taken it: apps#662 posted the header twice, and
// apps#660 posted the whole review fenced as a ```markdown block, header and footer
// included, which GitHub renders as unreadable raw source.
//
// Instructions are the fix; this is the seatbelt. Two rules keep a seatbelt from becoming
// the accident:
//
//   1. **Every marker is anchored to a position**, never matched anywhere in the body. The
//      reviews most likely to quote CI's header, footer or fence are reviews *of the
//      reviewer* — this file's own PRs. A bare indexOf on the header deletes everything
//      above the first mention, so quoting it in a finding would silently truncate the
//      review to nothing but that finding. Content below the first few lines can never
//      trigger a strip.
//   2. **An outer fence is unwrapped only on evidence that it wraps the whole report** —
//      a `markdown` info string, or CI's header as its first line. A report may open with
//      prose and close with a fenced checklist entry (Step 4 asks for one), and a
//      fence-counting heuristic reads that as an outer wrapper and eats both ends.
//
// When in doubt it leaves the text alone: the cost of a missed strip is one ugly comment,
// the cost of a wrong strip is a review that vanishes with no error anywhere.

import { readFileSync, writeFileSync, realpathSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const HEADER = '## 🤖 Automated apps review'
const FOOTER_OPEN = '<sub>Generated by the `apps-pr-review` agent.'
// How far into the report a marker may sit and still be envelope rather than content. A
// copied header is the first line, or sits under a one-line preamble.
const ENVELOPE_REACH = 3

const isFenceLine = (line) => /^\s*```/.test(line)
const isBlank = (line) => line.trim() === ''

/** Indices of the first `count` non-blank lines. */
function leadingNonBlank(lines, count) {
  const out = []
  for (let i = 0; i < lines.length && out.length < count; i++) if (!isBlank(lines[i])) out.push(i)
  return out
}

// A fence around the entire report. Accepts a one-line preamble above it ("Reviewing PR
// #660.") — that line is the agent talking, not review content, and it goes with the fence.
function dropOuterFence(lines) {
  const last = lines.length - 1
  if (last < 1 || !isFenceLine(lines[last])) return lines

  for (const open of leadingNonBlank(lines, 2)) {
    if (open >= last || !isFenceLine(lines[open])) continue
    const info = lines[open].trim().slice(3).trim().toLowerCase()
    const interior = lines.slice(open + 1, last)
    const firstInterior = interior.find((line) => !isBlank(line))
    // Evidence that this fence is the report's wrapper, not a code block of its own.
    const wrapsReport = info === 'markdown' || info === 'md' || firstInterior?.trim() === HEADER
    // ...and that the report's own fenced blocks inside it are balanced, so the closer on
    // the last line really is this fence's partner.
    const balanced = interior.filter(isFenceLine).length % 2 === 0
    if (wrapsReport && balanced) return interior
  }
  return lines
}

// CI's header, as a line of its own within reach of the top. A mention inside a finding is
// inline in backticks or inside a fenced block, never a bare line here.
function dropHeader(lines) {
  for (const i of leadingNonBlank(lines, ENVELOPE_REACH)) {
    if (lines[i].trim() !== HEADER) continue
    // Keep anything above it: a preamble line is content the author may want, and dropping
    // only the header is the lossless half of the fix. The blank line that followed the
    // header goes with it, or the report opens on a double blank.
    let rest = i + 1
    while (rest < lines.length && isBlank(lines[rest])) rest++
    return [...lines.slice(0, i), ...lines.slice(rest)]
  }
  return lines
}

// CI's footer, only as the last line of the report — with the `---` rule that introduces it.
function dropFooter(lines) {
  let end = lines.length - 1
  while (end >= 0 && isBlank(lines[end])) end--
  if (end < 0 || !lines[end].trimStart().startsWith(FOOTER_OPEN)) return lines

  let cut = end
  while (cut - 1 >= 0 && isBlank(lines[cut - 1])) cut--
  if (cut - 1 >= 0 && /^\s*-{3,}\s*$/.test(lines[cut - 1])) cut--
  return lines.slice(0, cut)
}

/**
 * @param {string} report raw agent output
 * @returns {string} the report body, without CI's header, footer or an outer code fence
 */
export function stripReviewEnvelope(report) {
  const lines = report.replace(/\r\n/g, '\n').trim().split('\n')
  const body = dropFooter(dropHeader(dropOuterFence(lines)))
  return `${body.join('\n').trim()}\n`
}

function main() {
  const [file] = process.argv.slice(2)
  if (!file) {
    console.error('usage: node scripts/strip-review-envelope.mjs <report.md>')
    process.exit(2)
  }
  const original = readFileSync(file, 'utf8')
  const stripped = stripReviewEnvelope(original)
  if (stripped === original) return
  console.log(`strip-review-envelope: removed CI's envelope from ${file}`)
  writeFileSync(file, stripped)
}

function realOrSelf(path) {
  try {
    return realpathSync(path)
  } catch {
    return path
  }
}

// Only run when invoked as a script — the test imports stripReviewEnvelope. Realpaths on
// both sides so the guard survives a symlinked checkout (bffless/apps#401).
if (process.argv[1] && realOrSelf(process.argv[1]) === realOrSelf(fileURLToPath(import.meta.url))) {
  main()
}
